def choose_lanes(bl):
    ys = [2400, 3000, 3600, 4200, 4800, 5400]
    base = build_top(bl, {k: ys[i] for i, k in enumerate(TOP_LANES)})
    e, _ = base.build()
    static = [(s['name'], a, b) for s in base.built if s['name'] not in LANE_SIGS for a, b in s['segs']]
    best = None
    for perm in itertools.permutations(ys):
        lanes = dict(zip(TOP_LANES, perm))
        d = build_top(bl, lanes)
        segs = []
        for name, polys in d.sigs:
            if name in LANE_SIGS:
                for p in polys:
                    segs += [(name, a, b) for a, b in zip(p, p[1:])]
        nx = bad = 0
        for i, s in enumerate(segs):
            for t in static:
                nx += cross(s[1:], t[1:]); bad += overlap(s[1:], t[1:])
            for t in segs[i + 1:]:
                if t[0] != s[0]:
                    nx += cross(s[1:], t[1:]); bad += overlap(s[1:], t[1:])
        if best is None or (bad, nx) < best[0]:
            best = ((bad, nx), lanes)
    return best


