def all_blocks():
    bl = dict(ALUCTL=B.blk_aluctl(), SIGNEXT=B.blk_signext(), CONTROL=B.blk_control(),
              MUXCTL=B.blk_muxctl(), HAZARD=B.blk_hazard(), FORWARD=B.blk_forward())
    for b in pipe_blocks():
        bl[b.name] = b
    return bl


